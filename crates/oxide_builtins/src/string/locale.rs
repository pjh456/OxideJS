/// 码点是否属 Mn/Cf（范围表二分判定，起点升序）。
fn is_mn_cf(cp: u32) -> bool {
    let idx = MN_CF_RANGES.partition_point(|&(lo, _)| lo <= cp);
    idx > 0 && cp <= MN_CF_RANGES[idx - 1].1
}

// ── Final Sigma 条件映射 ──────────────────────────────────────────────────

/// Final Sigma 条件小写映射：逐码点小写，其中 U+03A3（Σ）按条件规则取 σ/ς。
///
/// σ/ς 判定按原始单元序列（非变换后）：后向（索引升方向）跳过 Mn/Cf 单元
/// 存在可见字符 → σ；后向无且前向（索引降方向）跳过 Mn/Cf 存在可见字符 → ς；
/// 前后均无可见字符 → σ。孤立 surrogate 原样透传（与 toLowerCase 同口径）。
fn final_sigma_lower(units: &[u16]) -> Vec<u16> {
    let mut out = Vec::with_capacity(units.len());
    let mut i = 0;
    while i < units.len() {
        let u = units[i];
        if u == 0x03A3 {
            // 双向跳过 Mn/Cf 找最近可见字符（含行尾前的任意非 Mn/Cf 字符）。
            let mut j = i + 1;
            while j < units.len() && is_mn_cf(units[j] as u32) {
                j += 1;
            }
            let after_visible = j < units.len();
            let mut j = i;
            while j > 0 && is_mn_cf(units[j - 1] as u32) {
                j -= 1;
            }
            let before_visible = j > 0;
            out.push(if after_visible || !before_visible { 0x03C3 } else { 0x03C2 });
            i += 1;
            continue;
        }
        if (0xD800..=0xDBFF).contains(&u) && i + 1 < units.len() && (0xDC00..=0xDFFF).contains(&units[i + 1]) {
            // 代理对整体解码为码点小写后回写 UTF-16。
            let cp = (((u as u32) - 0xD800) << 10 | (units[i + 1] as u32 - 0xDC00)) + 0x10000;
            let c = char::from_u32(cp).expect("合法代理对必解码为合法码点");
            out.extend(c.to_lowercase().collect::<String>().encode_utf16());
            i += 2;
            continue;
        }
        if (0xD800..=0xDFFF).contains(&u) {
            out.push(u);
        } else if let Some(c) = char::from_u32(u as u32) {
            out.extend(c.to_lowercase().collect::<String>().encode_utf16());
        }
        i += 1;
    }
    out
}

