/// `String.prototype.toLocaleLowerCase`：locale 无关小写（与 toLowerCase 同表，
/// 增量 Final Sigma 条件映射）。
pub fn string_to_locale_lower_case<H: VmHost>(vm: &mut H, args: &[u8]) -> NativeResult {
    builtins_debug!("String.prototype.toLocaleLowerCase called with {} args", args.len());
    let s = try_string!(this_units(vm, args)).into_owned();
    let out = final_sigma_lower(&s);
    NativeResult::Ok(vm.new_string_units_owned(out))
}

/// `String.prototype.toLocaleUpperCase`：locale 无关大写（与 toUpperCase 同表，
/// 良形段映射，孤立 surrogate 单元原样保留）。
pub fn string_to_locale_upper_case<H: VmHost>(vm: &mut H, args: &[u8]) -> NativeResult {
    builtins_debug!("String.prototype.toLocaleUpperCase called with {} args", args.len());
    let s = try_string!(this_units(vm, args));
    let out = map_well_formed_segments(&s, |seg| seg.to_uppercase());
    NativeResult::Ok(vm.new_string_units_owned(out))
}

/// `String.prototype.localeCompare(compareString)`：基本档比较——两侧 NFC 归一后
/// 按 UTF-16 单元序（良形文本下与码元序等价）返回 -1/0/1。
///
/// # 边界与前提
/// - 第二参缺省或 undefined 落 "undefined" 串（规范基本档允许）；其余非字符串经
///   完整 ToString，Symbol 抛 TypeError；this 的 null/undefined/symbol 经
///   this_units 抛 TypeError。
///
/// # 注意事项
/// - 非 NFC 等价但 UCA 可分的串按单元序判（如 "ö" vs "o"），属基本档固有边界。
pub fn string_locale_compare<H: VmHost>(vm: &mut H, args: &[u8]) -> NativeResult {
    builtins_debug!("String.prototype.localeCompare called with {} args", args.len());
    use unicode_normalization::UnicodeNormalization;
    let a = try_string!(this_units(vm, args)).into_owned();
    let b = if args.len() > 1 && !vm.reg(args[1]).is_undefined() {
        try_string!(as_units(vm, vm.reg(args[1]))).into_owned()
    } else {
        "undefined".encode_utf16().collect()
    };
    // NFC 归一（良形段映射，孤立 surrogate 透传，与 normalize 同路径）。
    let a = map_well_formed_segments(&a, |seg| seg.nfc().collect());
    let b = map_well_formed_segments(&b, |seg| seg.nfc().collect());
    NativeResult::Ok(JsValue::int(match a.cmp(&b) {
        Ordering::Less => -1,
        Ordering::Equal => 0,
        Ordering::Greater => 1,
    }))
}

